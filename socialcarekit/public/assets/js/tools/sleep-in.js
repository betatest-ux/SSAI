// Sleep-in Pay & NMW Checker — fully client-side. No data leaves the browser.
(function () {
  'use strict';

  var form = document.getElementById('sleepin-form');
  if (!form) return;
  var resultEl = document.getElementById('si-result');
  var actionsEl = document.getElementById('si-actions');

  function currentRate(band) {
    var now = new Date();
    var best = null;
    (window.SCK_NMW_RATES || []).forEach(function (r) {
      if (r.band !== band) return;
      var eff = new Date(r.effective_from);
      if (eff <= now && (!best || eff > new Date(best.effective_from))) best = r;
    });
    return best;
  }

  function money(n) {
    return '£' + n.toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  form.addEventListener('submit', function (ev) {
    ev.preventDefault();
    var band = document.getElementById('si-band').value;
    var period = document.getElementById('si-period').value;
    var rate = parseFloat(document.getElementById('si-rate').value) || 0;
    var hours = parseFloat(document.getElementById('si-hours').value) || 0;
    var shifts = parseInt(document.getElementById('si-shifts').value, 10) || 0;
    var flat = parseFloat(document.getElementById('si-flat').value) || 0;
    var awake = parseFloat(document.getElementById('si-awake').value) || 0;

    var nmw = currentRate(band);
    if (!nmw) { return; }
    var nmwRate = parseFloat(nmw.hourly_rate);

    var countableHours = hours + awake;
    var totalPay = hours * rate + awake * rate + shifts * flat;
    // Note: some employers pay awake hours separately; we assume awake hours are
    // paid at basic rate on top of the flat allowance. The output explains this.

    if (countableHours <= 0) {
      resultEl.className = 'tool-result warn';
      resultEl.hidden = false;
      resultEl.innerHTML = '<h2>Enter your hours</h2><p>Add your worked hours (and any awake hours) so there is something to check.</p>';
      return;
    }

    var effective = totalPay / countableHours;
    var pass = effective >= nmwRate - 0.0001;
    var shortfall = (nmwRate * countableHours) - totalPay;
    var periodLabel = period === 'weekly' ? 'week' : 'month';

    resultEl.className = 'tool-result ' + (pass ? 'pass' : 'fail');
    resultEl.hidden = false;
    resultEl.innerHTML =
      '<h2>' + (pass ? '✓ PASS — at or above your minimum wage' : '✗ POSSIBLE BREACH — below your minimum wage') + '</h2>' +
      '<p class="result-figure">' + money(effective) + '/hour effective rate</p>' +
      '<table><tbody>' +
      '<tr><th scope="row">NMW-countable hours this ' + periodLabel + '</th><td>' + countableHours.toFixed(2) + ' (worked ' + hours.toFixed(2) + ' + awake during sleep-ins ' + awake.toFixed(2) + ')</td></tr>' +
      '<tr><th scope="row">Total pay counted</th><td>' + money(totalPay) + ' (basic pay + ' + shifts + ' sleep-in allowance' + (shifts === 1 ? '' : 's') + ' at ' + money(flat) + ')</td></tr>' +
      '<tr><th scope="row">Your NMW band</th><td>' + nmw.label + ' — ' + money(nmwRate) + '/hour</td></tr>' +
      (pass ? '' : '<tr><th scope="row">Shortfall this ' + periodLabel + '</th><td><strong>' + money(shortfall) + '</strong></td></tr>') +
      '</tbody></table>' +
      (pass
        ? '<p>Your average pay across NMW-countable time meets your band. Remember: time asleep on a sleep-in does not count as working time for NMW purposes (<em>Mencap v Tomlinson-Blake</em> [2021] UKSC 8), but your contract may still promise more — check it.</p>'
        : '<p>Across your NMW-countable time your average pay appears to fall below your legal minimum. This assumes your figures are right and that awake hours were paid at your basic rate. <strong>What to do:</strong> keep copies of rotas and payslips, raise it with your employer in writing, and see <a href="/rights/sleep-in-pay-explained/">what to do if you are underpaid</a> — ACAS (0300 123 1100) and HMRC\'s NMW complaint route can help.</p>') +
      '<p class="print-only">Generated by SocialCareKit sleep-in pay checker on ' + new Date().toLocaleDateString('en-GB') + '. Guidance only — not legal advice.</p>';
    actionsEl.hidden = false;
    resultEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  });
})();
