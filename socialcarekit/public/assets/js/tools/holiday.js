// Holiday Accrual Calculator — fully client-side.
(function () {
  'use strict';
  var form = document.getElementById('hol-form');
  if (!form) return;
  var resultEl = document.getElementById('hol-result');
  var actionsEl = document.getElementById('hol-actions');

  function mode() {
    return form.querySelector('input[name="hol-mode"]:checked').value;
  }
  form.querySelectorAll('input[name="hol-mode"]').forEach(function (r) {
    r.addEventListener('change', function () {
      form.querySelectorAll('[data-mode]').forEach(function (div) {
        div.hidden = div.getAttribute('data-mode') !== mode();
      });
      resultEl.hidden = true;
      actionsEl.hidden = true;
    });
  });

  function num(id) { return parseFloat(document.getElementById(id).value) || 0; }
  function money(n) { return '£' + n.toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 }); }
  function show(cls, html) {
    resultEl.className = 'tool-result ' + cls;
    resultEl.hidden = false;
    resultEl.innerHTML = html + '<p class="print-only">Generated by SocialCareKit holiday calculator on ' +
      new Date().toLocaleDateString('en-GB') + '. Guidance only — not legal advice.</p>';
    actionsEl.hidden = false;
    resultEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }

  form.addEventListener('submit', function (ev) {
    ev.preventDefault();
    var m = mode();

    if (m === 'regular') {
      var daysWeek = num('hol-days-week');
      var hoursDay = num('hol-hours-day');
      if (!daysWeek) { show('warn', '<h2>Enter your working pattern</h2>'); return; }
      var weeks = 5.6;
      var days = Math.min(weeks * daysWeek, 28);
      var capped = weeks * daysWeek > 28;
      show('pass',
        '<h2>Your statutory entitlement</h2>' +
        '<p class="result-figure">' + days.toFixed(1) + ' days' + (hoursDay ? ' (' + (days * hoursDay).toFixed(1) + ' hours)' : '') + '</p>' +
        '<p>5.6 weeks × ' + daysWeek + ' day' + (daysWeek === 1 ? '' : 's') + ' per week' +
        (capped ? ', capped at the 28-day statutory maximum' : '') +
        '. Bank holidays can be counted within this — check your contract, which may also give you more than the minimum.</p>');
    }

    if (m === 'irregular') {
      var worked = num('hol-worked');
      if (!worked) { show('warn', '<h2>Enter the hours you worked this pay period</h2>'); return; }
      var accrued = worked * 0.1207;
      var rolled = document.getElementById('hol-rolled').checked;
      var rate = num('hol-rate-i');
      var html = '<h2>Holiday accrued this pay period</h2>' +
        '<p class="result-figure">' + accrued.toFixed(2) + ' hours</p>' +
        '<p>' + worked.toFixed(2) + ' hours worked × 12.07% (Employment Rights (Amendment etc.) Regulations 2023 — leave years starting on/after 1 April 2024).</p>';
      if (rolled) {
        html += '<p><strong>Rolled-up holiday pay:</strong> your payslip should show a separately itemised uplift of ' +
          (rate ? money(worked * rate * 0.1207) : '12.07% of this period\'s pay') +
          '. If it is not shown as its own line, ask your employer to itemise it — that is a legal requirement.</p>';
      }
      show('pass', html);
    }

    if (m === 'leaver') {
      var start = document.getElementById('hol-ly-start').value;
      var leave = document.getElementById('hol-leave-date').value;
      var entitle = num('hol-entitle');
      var taken = num('hol-taken');
      var hoursDay = num('hol-hours-day-l');
      var rate = num('hol-rate-l');
      if (!start || !leave || !entitle) { show('warn', '<h2>Fill in the leave year start, leaving date and entitlement</h2>'); return; }
      var s = new Date(start), l = new Date(leave);
      var yearEnd = new Date(s); yearEnd.setFullYear(yearEnd.getFullYear() + 1);
      if (l < s || l > yearEnd) { show('warn', '<h2>Check your dates</h2><p>The leaving date should fall inside the leave year that starts on your chosen date.</p>'); return; }
      var fraction = (l - s) / (yearEnd - s);
      var accruedDays = entitle * fraction;
      var owedDays = accruedDays - taken;
      var owedHours = owedDays * hoursDay;
      var pay = rate && hoursDay ? owedHours * rate : null;
      var html = '<h2>Leaver calculation</h2>' +
        '<table><tbody>' +
        '<tr><th scope="row">Proportion of leave year worked</th><td>' + (fraction * 100).toFixed(1) + '%</td></tr>' +
        '<tr><th scope="row">Accrued to leaving date</th><td>' + accruedDays.toFixed(2) + ' days</td></tr>' +
        '<tr><th scope="row">Already taken</th><td>' + taken.toFixed(2) + ' days</td></tr>' +
        '<tr><th scope="row">' + (owedDays >= 0 ? 'Payable in lieu' : 'Taken over accrual') + '</th><td><strong>' +
        Math.abs(owedDays).toFixed(2) + ' days' + (hoursDay ? ' (' + Math.abs(owedHours).toFixed(2) + ' hours)' : '') + '</strong>' +
        (pay !== null && owedDays >= 0 ? ' ≈ <strong>' + money(pay) + '</strong> gross' : '') + '</td></tr>' +
        '</tbody></table>';
      if (owedDays >= 0) {
        html += '<p>Payment in lieu of accrued untaken statutory holiday is due on termination (WTR 1998, reg 14). It should appear on your final payslip.</p>';
      } else {
        html += '<p>You have taken more than you accrued. Your employer can only deduct the excess from final pay if your contract (or a written agreement) allows it.</p>';
      }
      show(owedDays >= 0 ? 'pass' : 'warn', html);
    }
  });
})();
