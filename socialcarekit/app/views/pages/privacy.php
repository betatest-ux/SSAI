    <h1>Privacy policy</h1>
    <p class="meta-line">Last updated: 30 July 2026</p>

    <div class="summary-box" data-reveal="left">
      <h2>In short</h2>
      <p>Our interactive tools run entirely in your browser — nothing you type into them is sent to or stored on our servers, ever. We keep no visitor profiles, set no analytics cookies, and collect personal data only when you deliberately give it to us (contact form or newsletter signup).</p>
    </div>

    <h2>The interactive tools</h2>
    <p>Every tool on this site (pay checkers, calculators, the notification decision tool, body map, visual timer, training matrix) is deliberately designed to run <strong>100% client-side</strong>:</p>
    <ul>
      <li>Data you enter is processed by JavaScript on your own device and is never transmitted to us.</li>
      <li>The body map holds its record only in the page's memory — closing the page destroys it.</li>
      <li>The training matrix saves to your browser's local storage on your device only. You control it entirely; clearing browser data deletes it.</li>
    </ul>

    <h2>What we do collect</h2>
    <ul>
      <li><strong>Aggregate page counts.</strong> We count how many times each page is viewed per day. This is a simple number — no cookies, no IP addresses stored, no device fingerprints, no individual-level data. That is why there is no cookie banner: there is nothing to consent to.</li>
      <li><strong>Site searches.</strong> We store search terms (not linked to any person) so we know which content to add.</li>
      <li><strong>Contact and error-report messages.</strong> If you write to us we hold your message, and your name and email if you chose to give them, for as long as needed to deal with it. Legal basis: legitimate interest in answering you.</li>
      <li><strong>Newsletter.</strong> If you sign up we store your email address and your confirmation (double opt-in). Legal basis: consent, which you can withdraw with the one-click unsubscribe link in every email or by contacting us. We do not share lists with anyone.</li>
      <li><strong>Server logs.</strong> Our hosting provider keeps standard, short-lived web server logs (IP address, request, time) for security and fault-finding.</li>
    </ul>

    <h2>What we never do</h2>
    <ul>
      <li>No advertising, ad networks or trackers.</li>
      <li>No sale or sharing of personal data.</li>
      <li>No profiling and no automated decision-making.</li>
    </ul>

    <h2>Your rights</h2>
    <p>Under UK GDPR you can ask us for a copy of the personal data we hold about you, ask us to correct or delete it, object to processing, or withdraw consent. Use the <a href="/contact/">contact form</a>. If you're unhappy with our answer you can complain to the Information Commissioner's Office (ico.org.uk).</p>

    <h2>Who we are</h2>
    <p>SocialCareKit is the data controller for the small amount of personal data described above. Contact us via the <a href="/contact/">contact page</a>.</p>
